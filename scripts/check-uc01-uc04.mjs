import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { Client, runtime, baseURL } from './lib/local-demo-client.mjs';

const checks = [];
const summary = { status: 'running', baseURL, startedAt: new Date().toISOString(), checks, records: {},
  scope: 'Real same-origin API / PostgreSQL 18 UC01 and UC04 acceptance',
  remaining: ['Independent member acceptance', 'Merge acceptance', 'Server handover and deployment'] };
const pass = name => { checks.push(name); console.log(`PASS ${name}`); };
const problem = (value, name) => assert.ok(value.type.endsWith('/problems/' + name), JSON.stringify(value));
const equipmentId = n => `20000000-0000-0000-0000-${String(n).padStart(12, '0')}`;
const reservations = '/api/v1/reservations';
const maintenance = '/api/v1/maintenance/cases';
const borrower = new Client(), other = new Client(), custodian = new Client(), technician = new Client(), admin = new Client(), approver = new Client();
try {
  const me = await borrower.login('borrower@example.test', 'BORROWER');
  const stranger = await other.login('borrower2@example.test', 'BORROWER');
  await custodian.login('custodian@example.test', 'CUSTODIAN');
  const tech = await technician.login('maintainer@example.test', 'MAINTAINER');
  const administrator = await admin.login('admin@example.test', 'ADMIN');
  await approver.login('approver@example.test', 'APPROVER');
  pass('all real role sessions established');
  const startAt = new Date(Date.now() + 86400000).toISOString();
  const endAt = new Date(Date.parse(startAt) + 3600000).toISOString();
  const listing = await borrower.request('GET', '/api/v1/equipment?' + new URLSearchParams({from: startAt, to: endAt, availableOnly: 'true', size: '50'}));
  const direct = listing.content.find(x => !x.requiresApproval && x.assetTag.startsWith('DEMO-')
    && ![equipmentId(6), equipmentId(8)].includes(x.equipmentId));
  const pending = listing.content.find(x => x.requiresApproval && x.assetTag.startsWith('DEMO-'));
  assert.ok(direct && pending, 'No free demo equipment; retain history and use another time window');
  pass('borrower searches real available equipment');
  const booking = { equipmentId: direct.equipmentId, startAt, endAt, purpose: 'UC01/UC04 acceptance' };
  const created = await borrower.request('POST', reservations, booking, 201);
  assert.equal(created.status, 'CONFIRMED'); summary.records.reservationId = created.reservationId;
  pass('direct reservation is confirmed');
  problem(await other.request('POST', reservations, booking, 409), 'reservation-conflict');
  pass('overlap rejected on real database');
  await other.request('GET', `${reservations}/${created.reservationId}`, undefined, 404);
  await other.request('POST', `${reservations}/${created.reservationId}/cancel`, undefined, 404);
  pass('other borrower cannot read or cancel personal reservation');
  await borrower.request('POST', `${reservations}/${created.reservationId}/cancel`, undefined, 403, false);
  pass('cancellation requires CSRF');
  const cancelled = await borrower.request('POST', `${reservations}/${created.reservationId}/cancel`);
  assert.equal(cancelled.status, 'CANCELLED'); assert.equal(cancelled.cancellable, false);
  pass('borrower cancels confirmed reservation');
  problem(await borrower.request('POST', `${reservations}/${created.reservationId}/cancel`, undefined, 409), 'not-cancellable');
  pass('repeated cancellation is a contracted conflict');
  const replacement = await other.request('POST', reservations, booking, 201);
  await other.request('POST', `${reservations}/${replacement.reservationId}/cancel`);
  pass('cancellation immediately releases occupied interval');
  const p = await borrower.request('POST', reservations, {...booking, equipmentId: pending.equipmentId}, 201);
  assert.equal(p.status, 'PENDING_APPROVAL');
  const approved = await approver.request('POST', `/api/v1/approvals/${p.reservationId}/decision`, {decision: 'APPROVED', expectedVersion: p.version, comment: 'Integrated acceptance'});
  assert.equal(approved.reservation.status, 'CONFIRMED');
  await borrower.request('POST', `${reservations}/${p.reservationId}/cancel`);
  pass('UC01 pending request uses existing UC02 approval service');
  await borrower.request('POST', reservations, {...booking, equipmentId: equipmentId(7)}, 404);
  pass('retired equipment cannot be booked');
  // Use a distinct repair item. Snapshot reads use the privileged, existing operator API.
  const faultId = equipmentId(6);
  const casesBefore = await custodian.request('GET', `/api/v1/maintenance/equipment/${faultId}/cases`);
  const unknownLoan = await borrower.request('POST', maintenance, { equipmentId: faultId, loanId: randomUUID(), faultDescription: 'Invalid link must roll back' }, 400);
  problem(unknownLoan, 'validation');
  assert.deepEqual(await custodian.request('GET', `/api/v1/maintenance/equipment/${faultId}/cases`), casesBefore);
  const unchanged = await borrower.request('GET', '/api/v1/equipment?q=DEMO-MEA-01');
  assert.equal(unchanged.content[0].status, 'AVAILABLE');
  pass('missing linked loan has no case or equipment side effects');
  const activeStart = new Date(Date.now() + 3000).toISOString();
  const active = await borrower.request('POST', reservations, {...booking, startAt: activeStart, endAt: new Date(Date.parse(activeStart) + 3600000).toISOString()}, 201);
  await new Promise(resolve => setTimeout(resolve, Math.max(0, Date.parse(activeStart) - Date.now() + 100)));
  const loan = await custodian.request('POST', '/api/v1/loans', {reservationId: active.reservationId, borrowerId: me.userId, expectedVersion: active.version, identityConfirmed: true}, 201);
  summary.records.loanId = loan.loanId;
  problem(await borrower.request('POST', `${reservations}/${active.reservationId}/cancel`, undefined, 409), 'not-cancellable');
  pass('checked-out reservation cannot be cancelled');
  await borrower.request('POST', maintenance, {equipmentId: faultId, loanId: loan.loanId, faultDescription: 'Wrong equipment link'}, 400);
  assert.deepEqual(await custodian.request('GET', `/api/v1/maintenance/equipment/${faultId}/cases`), casesBefore);
  pass('loan linked to another equipment is rejected without writes');
  await custodian.request('POST', `/api/v1/loans/${loan.loanId}/return`, {expectedVersion: loan.version, condition: 'GOOD'});
  const fault = await borrower.request('POST', maintenance, {equipmentId: faultId, faultDescription: 'UC04 acceptance connector fault'}, 201);
  summary.records.maintenanceCaseId = fault.maintenanceCaseId;
  assert.equal(fault.reportedBy, me.userId); assert.equal(fault.status, 'OPEN');
  pass('reporter identity comes from authenticated session');
  problem(await borrower.request('POST', reservations, {...booking, equipmentId: faultId}, 409), 'equipment-unavailable');
  const unavailable = await borrower.request('GET', `/api/v1/equipment/${faultId}/availability?` + new URLSearchParams({from:startAt,to:endAt}));
  assert.equal(unavailable.available, false); assert.equal(unavailable.openMaintenance, true);
  pass('open fault blocks both availability and reservation');
  await borrower.request('POST', `${maintenance}/${fault.maintenanceCaseId}/assignment`, {technicianId: tech.userId}, 403);
  await admin.request('POST', `${maintenance}/${fault.maintenanceCaseId}/assignment`, {technicianId: administrator.userId}, 400);
  pass('unauthorized assignment and non-technician selection are rejected');
  await technician.request('GET', `${maintenance}/${fault.maintenanceCaseId}`, undefined, 403);
  await technician.request('POST', `${maintenance}/${fault.maintenanceCaseId}/start`, undefined, 403);
  pass('unassigned maintainer cannot read or start case');
  const assigned = await custodian.request('POST', `${maintenance}/${fault.maintenanceCaseId}/assignment`, {technicianId: tech.userId});
  assert.equal(assigned.status, 'ASSIGNED');
  await borrower.request('POST', `${maintenance}/${fault.maintenanceCaseId}/start`, undefined, 403);
  await admin.request('POST', `${maintenance}/${fault.maintenanceCaseId}/resolve`, {resolutionNote:'Admin cannot impersonate technician'}, 403);
  pass('assignment does not let borrower or admin perform technician work');
  const working = await technician.request('POST', `${maintenance}/${fault.maintenanceCaseId}/start`);
  assert.equal(working.status, 'IN_PROGRESS');
  await technician.request('POST', `${maintenance}/${fault.maintenanceCaseId}/diagnosis`, {detail:'Loose connector'});
  await technician.request('POST', `${maintenance}/${fault.maintenanceCaseId}/repair-actions`, {detail:'Reseated connector'});
  const resolved = await technician.request('POST', `${maintenance}/${fault.maintenanceCaseId}/resolve`, {resolutionNote:'Repaired and function tested'});
  assert.equal(resolved.status, 'RESOLVED');
  pass('assigned technician completes diagnosis repair and resolution');
  const history = await technician.request('GET', `${maintenance}/${fault.maintenanceCaseId}/history`);
  assert.deepEqual(history.map(x => x.action), ['REPORT_FAULT','ASSIGN','START','RECORD_DIAGNOSIS','RECORD_REPAIR_ACTION','RESOLVE']);
  pass('complete maintenance history persisted');
  await technician.request('POST', `${maintenance}/${fault.maintenanceCaseId}/notes`, {detail:'Terminal write must fail'}, 409);
  assert.deepEqual(await technician.request('GET', `${maintenance}/${fault.maintenanceCaseId}/history`), history);
  pass('terminal case refuses work without new history');
  const repaired = await borrower.request('GET', '/api/v1/equipment?q=DEMO-MEA-01');
  assert.equal(repaired.content[0].status, 'AVAILABLE');
  const afterRepair = await borrower.request('POST', reservations, {...booking, equipmentId: faultId}, 201);
  await borrower.request('POST', `${reservations}/${afterRepair.reservationId}/cancel`);
  pass('resolved equipment is available and reservable again');
  const linked = await borrower.request('POST', maintenance, {equipmentId: direct.equipmentId, loanId: loan.loanId, faultDescription:'Valid returned-loan link'}, 201);
  assert.equal(linked.loanId, loan.loanId);
  await custodian.request('POST', `${maintenance}/${linked.maintenanceCaseId}/assignment`, {technicianId: tech.userId});
  await technician.request('POST', `${maintenance}/${linked.maintenanceCaseId}/start`);
  await technician.request('POST', `${maintenance}/${linked.maintenanceCaseId}/resolve`, {resolutionNote:'Historical loan linkage verified'});
  pass('valid returned loan links to matching equipment and can be repaired');
  for (const client of [borrower, other, custodian, technician, admin, approver]) await client.request('POST', '/api/v1/auth/logout', undefined, 204);
  assert.ok(stranger.userId !== me.userId);
  summary.status = 'passed';
} catch (error) { summary.status = 'failed'; summary.failure = error.message; throw error; }
finally {
  summary.finishedAt = new Date().toISOString();
  fs.writeFileSync(path.join(runtime, 'uc01-uc04-summary.json'), JSON.stringify(summary, null, 2));
}
