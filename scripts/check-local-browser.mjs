import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
const repo=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const require=createRequire(path.join(repo,'frontend/package.json'));
const {chromium}=require('@playwright/test');
const runtime=path.join(repo,'.cache/local-demo');
const read=name=>JSON.parse(fs.readFileSync(path.join(runtime,name),'utf8').replace(/^\uFEFF/,''));
const state=read('state.json'), access=read('access.json'), smoke=read('smoke-summary.json');
assert.equal(path.resolve(state.repo),repo,'Only this checkout may be verified');
assert.equal(smoke.status,'passed','Run the real API smoke test before browser verification');
const evidence=path.join(repo,'docs/evidence/local-demo');
fs.mkdirSync(evidence,{recursive:true});
const browser=await chromium.launch({headless:true});
const failures=[];
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 page.on('pageerror',error=>failures.push(error.message));
 await page.goto(`http://127.0.0.1:${state.webPort}/login`);
 await page.getByLabel('Email address').fill('borrower@example.test');
 await page.getByLabel('Password',{exact:true}).fill(access.demoPassword);
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await page.getByRole('heading',{level:1,name:/^Welcome/}).waitFor();
 await page.getByRole('link',{name:'Find equipment',exact:true}).click();
 await page.waitForURL('**/equipment');
 await page.getByText('Sony mirrorless camera',{exact:true}).waitFor();
 await page.screenshot({path:path.join(evidence,'01-equipment-desktop.png'),fullPage:true});
 await page.getByRole('link',{name:'My reservations',exact:true}).click();
 await page.waitForURL('**/reservations');
 await page.getByText(smoke.equipmentName??'Sony mirrorless camera',{exact:true}).waitFor();
 await page.screenshot({path:path.join(evidence,'02-reservations-desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('link',{name:'Find equipment'}).click();
 await page.getByText('Sony mirrorless camera',{exact:true}).waitFor();
 await page.screenshot({path:path.join(evidence,'03-equipment-mobile.png'),fullPage:true});
 const dimensions=await page.evaluate(()=>({viewport:innerWidth,body:document.body.scrollWidth,html:document.documentElement.scrollWidth}));
 assert.ok(Math.max(dimensions.body,dimensions.html)<=dimensions.viewport+2,`Mobile document overflows: ${JSON.stringify(dimensions)}`);
 assert.deepEqual(failures,[],'Uncaught browser exceptions');
 fs.writeFileSync(path.join(runtime,'browser-summary.json'),JSON.stringify({status:'passed',checks:['real browser login','equipment navigation/data','real reservation history','desktop screenshot','mobile screenshot/no document overflow','no uncaught browser exceptions'],screenshots:fs.readdirSync(evidence).filter(x=>x.endsWith('.png')),dimensions,finishedAt:new Date().toISOString()},null,2));
 console.log(JSON.stringify({status:'passed',evidence,checks:6,dimensions}));
} finally {await browser.close();}
